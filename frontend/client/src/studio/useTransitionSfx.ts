/**
 * useTransitionSfx — fires a one-shot ``<audio>`` element each time the
 * Remotion Player crosses a transition boundary, so the in-browser preview
 * gets the same fade/swipe/whoosh stingers the server-side render will mix
 * into the final MP4 via ``_build_sfx_mix``.
 *
 * Listens to the same RAF polling loop the playhead uses (no extra
 * subscriptions). Tracks the previous frame so we only fire when the
 * playhead CROSSES a boundary going forward — scrubbing backwards or
 * pausing on a boundary doesn't re-trigger the sting.
 */
import { useEffect, useRef } from "react";

import type { PlayerRef } from "@remotion/player";

import type { EditSpec, TransitionType } from "./types";

/** Mirror of TRANSITION_CATALOG[type].sfx_file in
 *  src/features/studio/transition_catalog.py. Keep both in sync — every
 *  TransitionType that has an SFX must have an entry here, and the file
 *  must exist in frontend/client/public/sfx/ (generated by
 *  scripts/synth_studio_sfx.py). */
const SFX_PATH: Record<TransitionType, string | null> = {
  cut: null,
  fade: "/sfx/fade.wav",
  dissolve: "/sfx/dissolve.wav",
  swipe: "/sfx/swipe.wav",
  slide_up: "/sfx/swipe.wav",
  slide_down: "/sfx/swipe.wav",
  zoom_in: "/sfx/zoom.wav",
  zoom_out: "/sfx/zoom.wav",
  zoom_blur: "/sfx/zoom.wav",
  rgb_split: "/sfx/glitch.wav",
  glitch_shake: "/sfx/glitch.wav",
  vhs: "/sfx/vhs.wav",
  flash_white: "/sfx/flash.wav",
  fade_to_black: "/sfx/fade.wav",
  whoosh: "/sfx/whoosh.wav",
};

interface Options {
  playerRef: React.RefObject<PlayerRef | null>;
  spec: EditSpec | null;
  fps: number;
}

export function useTransitionSfx({ playerRef, spec, fps }: Options): void {
  // Stable audio element per type so we don't allocate on every fire.
  const audioCacheRef = useRef<Map<string, HTMLAudioElement>>(new Map());
  const lastFrameRef = useRef<number>(-1);

  useEffect(() => {
    if (!spec) return;
    const tx = spec.transitions;
    if (!tx?.enabled || !tx.sfx_enabled) return;
    const src = SFX_PATH[tx.type];
    if (!src) return;

    // Precompute boundaries: B-roll start/end + camera-cut boundaries.
    // Match the backend's logic in render._collect_{broll,camera}_boundaries
    // so preview SFX timing == render SFX timing.
    const boundaries: number[] = [];
    if (spec.broll?.enabled) {
      for (const c of spec.broll.clips ?? []) {
        boundaries.push(c.start);
        if (c.end - c.start > 0.5) boundaries.push(c.end);
      }
    }
    if (spec.camera?.tracks?.length) {
      const cuts = [...spec.camera.tracks].sort((a, b) => a.start - b.start);
      for (let i = 0; i < cuts.length - 1; i++) {
        if (cuts[i].subject_id !== cuts[i + 1].subject_id) {
          boundaries.push(cuts[i + 1].start);
        }
      }
    }
    boundaries.sort((a, b) => a - b);
    // Dedupe near-collisions so a camera cut + B-roll edge at the same
    // moment don't stutter.
    const deduped: number[] = [];
    for (const b of boundaries) {
      if (!deduped.length || b - deduped[deduped.length - 1] > 0.15) {
        deduped.push(b);
      }
    }
    if (deduped.length === 0) return;

    // Preload a SHARED <audio> so the first fire isn't delayed by network.
    // We clone-node before each play so overlapping stingers don't cut
    // each other off.
    let baseAudio = audioCacheRef.current.get(src);
    if (!baseAudio) {
      baseAudio = new Audio(src);
      baseAudio.preload = "auto";
      baseAudio.volume = 0.6;
      audioCacheRef.current.set(src, baseAudio);
    }
    const audio = baseAudio;

    let raf = 0;
    const loop = () => {
      raf = requestAnimationFrame(loop);
      const player = playerRef.current;
      if (!player) return;
      let frame: number;
      try {
        frame = player.getCurrentFrame();
      } catch {
        return;
      }
      const t = frame / fps;
      const prev = lastFrameRef.current;
      const prevT = prev / fps;
      lastFrameRef.current = frame;
      // Only fire when we genuinely advance forward by a small window —
      // skip on initial mount (prev = -1) and on backwards seeks.
      if (prev < 0 || frame <= prev) return;
      // Cross-detection: any boundary in (prevT, t].
      for (const b of deduped) {
        if (b > prevT && b <= t) {
          try {
            // Clone so overlapping fires don't kill each other. Disposable.
            const inst = audio.cloneNode(true) as HTMLAudioElement;
            inst.volume = 0.6;
            void inst.play().catch(() => {
              // Browsers can block playback before user gesture; silently
              // ignore. Once the user clicks Play, subsequent SFX fire.
            });
          } catch {
            // ignore
          }
        }
      }
    };
    raf = requestAnimationFrame(loop);
    return () => cancelAnimationFrame(raf);
  }, [
    playerRef,
    fps,
    spec?.transitions?.enabled,
    spec?.transitions?.type,
    spec?.transitions?.sfx_enabled,
    spec?.transitions?.duration_ms,
    spec?.broll?.enabled,
    // Deep-stringify the boundaries so dependency changes when clips/cuts
    // move. Cheap because both arrays are tiny.
    JSON.stringify(spec?.broll?.clips ?? []),
    JSON.stringify(spec?.camera?.tracks ?? []),
  ]);
}
