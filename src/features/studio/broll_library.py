def describe_featured_broll() -> List[Dict[str, Any]]:
    """JSON-serializable list of featured B-roll clips for the panel."""
    return list(FEATURED_BROLL.values())


def get_local_path(clip_id: str) -> Optional[str]:
    """On-disk path for a bundled B-roll, or None if not present."""
    if clip_id not in FEATURED_BROLL:
        return None
    path = os.path.join(_ASSETS_DIR, f"{clip_id}.mp4")
    return path if os.path.exists(path) else None


