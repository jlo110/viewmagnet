"""Default B-roll quick-pick library (Week 6 followup).

Mirrors ``background_catalog`` but for the B-roll overlay lane: a small
set of procedural mp4s bundled with the repo so the user can drop
something onto the timeline in one click without configuring the Pexels
API. The Pexels search box in the B-roll panel remains the primary way
to get real footage; this just removes the "blank page" problem.

Assets:
    src/assets/broll/<id>.mp4
    src/assets/broll/<id>.jpg
Generated by:
    scripts/synth_default_broll.py
Served at:
    GET /studio/assets/broll/<id>.{mp4,jpg}
"""
from __future__ import annotations

import os
from typing import Any, Dict, List, Optional


_ASSETS_DIR = os.path.abspath(
    os.path.join(
        os.path.dirname(__file__),
        "..", "..", "assets", "broll",
    )
)

# See background_catalog._PUBLIC_URL_PREFIX for the ``/api/`` rationale.
_PUBLIC_URL_PREFIX = "/api/studio/assets/broll"


def _entry(
    *,
    id: str,
    label: str,
    category: str,
    description: str,
    duration_seconds: float = 4.0,
) -> Dict[str, Any]:
    """Shape matches the BackgroundCatalogEntry frontend type so the panel
    can render either with the same card component."""
    return {
        "id": id,
        "label": label,
        "category": category,
        "description": description,
        "preview_thumbnail": f"{_PUBLIC_URL_PREFIX}/{id}.jpg",
        "download_url": f"{_PUBLIC_URL_PREFIX}/{id}.mp4",
        "duration_seconds": duration_seconds,
        "source": "bundled",
    }


