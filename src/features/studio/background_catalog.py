# Absolute path on disk for the bundled background loops (matched by the
# static mount in ``src/api/main.py``). Resolved once at import time so
# ``get_local_path()`` doesn't redo it per call.
_ASSETS_DIR = os.path.abspath(
    os.path.join(
        os.path.dirname(__file__),
        "..", "..", "assets", "backgrounds",
    )
)

# URL prefix the frontend uses to fetch the bundled assets.
#
# The Vite dev server proxies ``/api/*`` to the backend (see
# ``frontend/vite.config.ts``) and Vite STRIPS the ``/api/`` prefix
# before forwarding — so a frontend request for
# ``/api/studio/assets/backgrounds/aurora_violet.mp4`` hits the FastAPI
# static mount at ``/studio/assets/backgrounds/aurora_violet.mp4``.
#
# In production the reverse proxy is configured the same way (``/api/*``
# → backend). Returning ``/api/studio/assets/...`` here means catalog
# entries are usable directly as ``<img src>``/``<video src>`` values
# without any client-side rewriting.
_PUBLIC_URL_PREFIX = "/api/studio/assets/backgrounds"


def _entry(
    *,
    id: str,
    label: str,
    category: str,
    attribution: str,
    duration_seconds: float = 6.0,
) -> Dict[str, Any]:
    """Build a FEATURED_LOOPS dict for one bundled asset.

    Centralized so we don't drift between the script's filenames and the
    public-facing catalog when a new loop is added."""
    return {
        "id": id,
        "label": label,
        "category": category,
        "preview_thumbnail": f"{_PUBLIC_URL_PREFIX}/{id}.jpg",
        "download_url": f"{_PUBLIC_URL_PREFIX}/{id}.mp4",
        "duration_seconds": duration_seconds,
        "attribution": attribution,
    }


