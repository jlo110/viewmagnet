"""Curated background-loop catalog + Pexels search proxy (Week 6).

Hybrid sourcing strategy:

  1. ``FEATURED_LOOPS`` is a hand-picked list of seamless background loops
     bundled with the repo. The MP4 + JPG files live under
     ``src/assets/backgrounds/`` and are generated procedurally by
     ``scripts/synth_background_loops.py`` (no external dependency, no
     rights-clearance, works on a fresh clone). They're served statically
     by FastAPI at ``/studio/assets/backgrounds/<id>.mp4``.

  2. ``search_pexels_videos`` proxies the Pexels API for the BackgroundsPanel
     "Search Pexels" tab. Results are normalized into the same shape the
     featured catalog uses so the frontend renders them with the same card
     component. Returns ``[]`` (not an error) when ``PEXELS_API_KEY`` isn't
     configured so dev environments degrade gracefully.

The render job consumes either source via ``EditSpec.background_loop``:

    BackgroundLoop(source="catalog", catalog_id="aurora_violet")
    BackgroundLoop(source="pexels",  clip_url="https://...")

Both paths funnel into ``render._ensure_background_loop`` which short-
circuits to a direct file read for bundled assets (no HTTP roundtrip)
and falls back to httpx for everything else.
"""
