def get_local_path(catalog_id: str) -> Optional[str]:
    """Return the on-disk path for a bundled featured loop, or None.

    Used by ``render._ensure_background_loop`` to skip the http download
    when the catalog entry refers to a file already in our repo.
    """
    if catalog_id not in FEATURED_LOOPS:
        return None
    path = os.path.join(_ASSETS_DIR, f"{catalog_id}.mp4")
    return path if os.path.exists(path) else None


def describe_featured_loops() -> List[Dict[str, Any]]:
    """JSON-serializable list of featured loops for ``GET /studio/backgrounds``.

    Includes entries whose ``download_url`` is still a placeholder so the
    UI can show the full curated grid even on a fresh checkout — the
    backend will fall back to the thumbnail as a still background when a
    user picks one that hasn't been seeded yet.
    """
    return list(FEATURED_LOOPS.values())


def get_featured(catalog_id: str) -> Dict[str, Any]:
    """Lookup a featured loop by id. Raises KeyError on miss so the
    render job fails loudly rather than silently dropping a background."""
    if catalog_id not in FEATURED_LOOPS:
        raise KeyError(f"unknown featured loop '{catalog_id}'")
    return FEATURED_LOOPS[catalog_id]


# ---------------------------------------------------------------------------
# Pexels search proxy
# ---------------------------------------------------------------------------


async def search_pexels_videos(query: str, per_page: int = 12) -> List[Dict[str, Any]]:
    """Search Pexels for loop-friendly background videos.

    Returns standardized dicts matching the ``BackgroundSearchItem``
    response model in the API layer. Filters out videos shorter than 10s
    (too short to read as a loop) and prefers HD quality so the
    background isn't pixelated when scaled across the canvas.

    Run as a thread executor — ``PexelsClient`` is a sync ``httpx.Client``
    and FastAPI hands us an async context, so we shouldn't block the
    event loop on the network call.
    """
    if not os.getenv("PEXELS_API_KEY"):
        raise RuntimeError("PEXELS_API_KEY not configured")

    from src.features.broll_finder import PexelsClient

    def _run() -> List[Dict[str, Any]]:
        client = PexelsClient()
        clips = client.search_videos(query=query, per_page=per_page)
        out: List[Dict[str, Any]] = []
        for c in clips:
            if c.duration < 10:
                # Avoid sub-10s clips — they show the loop seam too quickly.
                continue
            out.append(
                {
                    "id": c.id,
                    "source": "pexels",
                    "label": c.title or "Untitled",
                    "preview_thumbnail": c.thumbnail_url or c.preview_url,
                    "download_url": c.download_url,
                    "duration_seconds": float(c.duration),
                    "width": int(c.width or 0),
                    "height": int(c.height or 0),
                }
            )
        return out

    return await asyncio.to_thread(_run)


